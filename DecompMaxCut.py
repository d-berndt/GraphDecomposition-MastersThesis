def get_graph(G):
    """Generate a weighted graph
    
    Args:
        G: nx.graph, list or np.array
    Returns:
        L: graph generated by G with all edges assigned a weight
    
    """
    
    if isinstance(G, nx.Graph):
        L = G.copy()
        for E in L.edges:
            if 'weight' not in L.get_edge_data(E[0],E[1]):
                L[E[0]][E[1]]['weight'] = 1
        
    elif isinstance(G, np.ndarray):
        L = nx.from_numpy_array(G)
        
    elif isinstance(G, list):
        L = nx.from_numpy_array(np.array(G))
        
    return L

def S_Array(K):
    """Generate an list S that contains all possible s∈{0,1}|K| as 
    dictionaries without redundant symmetric entries (e.g. (0,0)^=(1,1))
    
    Args:
        K: list of nodes.
    Returns:
        s: list of dictionaries.
    """
    
    L = len(K)
    
    """Create a list of lists containing all possible s"""
    s1 = list(itertools.product([0, 1], repeat = L)) 

    """Remove symmetric values, e.g. (0,0,0)^=(1,1,1)"""
    s1 = s1[:int((2**L)/2)]      
        
    """Create a list of dictionaries"""
    s = []
    s2 = {}
    for m in range(len(s1)):
        for n in range(L):
            s2[K[n]] = s1[m][n]
        s.append(s2.copy())
        
    return s

def complete_graph_from_list(L, create_using = None):
    """Generate a fully connected graph with nodes in list L.
    
    Args:
        L: list of nodes.
    Returns:
        G: nx.graph.
    """
    
    G = nx.empty_graph(L,create_using)
    if len(L) > 1:
        if G.is_directed():
            edges = itertools.permutations(L,2)
        else:
            edges = itertools.combinations(L,2)
        G.add_edges_from(edges)
        
    return G

def VertexSep(G: nx.Graph, method="metis"):
    """Return a vertex separator K of G and remaining sets V1, V2 with V1 >= V2.

    Args:
        G: networkx graph
        method: "networkx" or "metis"

    Returns:
        K: list of separator nodes
        V1: larger remaining side
        V2: smaller remaining side
    """

    if method == "metis":
        K, A, B = nxmetis.vertex_separator(G)

    elif method == "networkx":
        K = list(nx.minimum_node_cut(G))
        H = G.copy()
        H.remove_nodes_from(K)

        comps = list(nx.connected_components(H))

        if len(comps) < 2:
            return K, list(G.nodes()), []

        comps = sorted(comps, key=len, reverse=True)

        """Largest component on one side, everything else merged on the other."""
        A = list(comps[0])
        B = []
        for comp in comps[1:]:
            B.extend(comp)

    else:
        raise ValueError("method must be 'networkx' or 'metis'")

    #Sort sets
    if len(A) >= len(B):
        V1, V2 = A, B
    else:
        V1, V2 = B, A

    return list(K), V1, V2

def search_dict(Vbitslist, result, K):
    """Searches the list of dictionaries Vbitslist to find a subdict which is
    equal to a given dict result.
    
    Args:
        Vbitslist: list of dictionaries
        result: dictionary
        K: list
    Returns:
        filtered_data: result appended by bits for nodes in V2.
    """

    """Initiate working dictionary."""
    filtered_data = Vbitslist.copy()
    
    """Search for result in Vbitslist."""
    for n in K:
        filtered_data = [item for item in filtered_data if item[str(n)] == result[str(n)]]
        
    """If no result is found, flip bits in results dictionary."""
    if filtered_data == []:
        filtered_data = Vbitslist.copy()
        flipped = {}
        
        #flip bits
        for n in K:
            flipped[str(n)] = 1 - result[str(n)]
        for n in K:
            filtered_data = [item for item in filtered_data if item[str(n)] == flipped[str(n)]]
        #flip bits back
        for n in filtered_data[0]:
            filtered_data[0][n] = 1-filtered_data[0][n]
        
    return filtered_data[0]

def result_to_dict(result, G: nx.Graph):
    """Takes the result of a MaxCut problem and makes sure it is a dictionary.
    
    Args:
        result: result (bit allocation of the nodes) of a MaxCut problem
        G: Graph of the MaxCut problem
    Returns:
        result_dict: result as a dictionary
    """    

    if isinstance(result, (list)):
        result_dict = {}
        i = 0
        for n in G.nodes:
            result_dict[str(n)] = result[i]
            i += 1   
    elif isinstance(result, (str)):
        result_dict = {}
        i = 0
        for n in G.nodes:
            result_dict[str(n)] = int(result[i])
            i += 1 
    else:
        result_dict = result
             
    return result_dict

def Obj_from_bits(Graph: nx.Graph, bits):
    """Calculates the cut of a graph for a given set of node allocations
    
    Args:
        G: Graph
        bits: node assignments (0 or 1)
    Returns:
        Obj: value of the cut
    """ 
    
    Obj = 0
    for i, j in Graph.edges:
        if bits[str(i)] != bits[str(j)]:
            Obj += Graph.edges[i, j]['weight']
    return Obj

def undo_kronecker_qubits(C):
    """
    Undos a Kronecker product of 2x1 qubits to recover the original qubits

    Args:
        C: The Kronecker product vector.
    Returns:
        qubits: A list of the recovered qubits.
    """
    
    N = C.shape[0]  #Get the length of C
    num_qubits = int(np.log2(N))  #Number of qubits
    
    qubits = []
    current_matrix = C.copy()

    for _ in range(num_qubits):
        """Reshape to isolate one qubit"""
        current_matrix = current_matrix.reshape(2, -1)
        
        """SVD to find the best rank-1 approximation"""
        U, S, Vt = np.linalg.svd(current_matrix, full_matrices=False)
        qubit = U[:, 0] #First column of U is the estimated qubit
        qubit /= np.linalg.norm(qubit) #Normalize

        """Add qubit to qubit list."""
        qubits.append(qubit)
        
        """Remove the extracted qubit by dividing out its contribution"""
        current_matrix = (1 / S[0]) * (U[:, 0].T @ current_matrix)

    return qubits

def measure_qubit(qubit):
    """
    Simulate a measurement of a qubit.
    
    Args:
        qubit: 2x1 qubit state vector.
    Returns:
        result: 0 or 1.
    """
    
    probabilities = np.abs(qubit.flatten())**2 # Compute probabilities
    probabilities /= np.sum(probabilities) # Normalize
    result = np.random.choice([0, 1], p=probabilities) # Sample measurement outcome
    
    return result

def qaoa_failed(result, angles):
    return (all(r == 0 for r in result) and angles[0] == angles[-1])

def is_trivial_subproblem(H, fixed, free_qubits):
    """
    Return True if the problem is trivial.
    """
    if len(free_qubits) == 0:
        return True  # nothing to optimize

    #Enumerate all 2^k assignments for free qubits
    values = []
    for bits_free in itertools.product([0, 1], repeat=len(free_qubits)):
        bits = {str(n): fixed.get(n, 0) for n in H.nodes()}
        for q, val in zip(free_qubits, bits_free):
            bits[str(q)] = val
        values.append(Obj_from_bits(get_graph(H), bits))

    #If all cut values are the same, the subproblem is trivial
    return all(v == values[0] for v in values)

def solve_trivial_subproblem(H, fixed, free_qubits):
    bits = {str(n): fixed.get(n, 0) for n in H.nodes()}
    return bits

def decode_qaoa_result(H, p, fixed, qubits, shots=500):
    """
    Measure qubits and build a full bit assignment.

    Args:
        H: Problemgraph as nx.Graph.
        p: Problem instance.
        fixed : dictionary of fixed nodes.
        qubits : list of qubit.
        shots: shots
        
    Returns:
        best_bits: bit assignment associated with the best measured objective value.
        best_obj: best measured objective value.
        shots: shots
    """

    """Initiate lists."""
    best_bits = []
    best_obj = float("-inf")

    for _ in range(shots):
        #Measure all free qubits once
        measurements = []
        for i in range(p.num_var):
           q = measure_qubit(qubits[i])
           measurements.append(q)
    
        #Build dictionary with free qubits from measurements
        bits = {}
        a=0
        for b in p.free_qubits:
            bits[str(b)] = int(measurements[a])
            a+=1
        
        #Add fixed bits
        for b in fixed:
            bits[str(b)] = fixed[b]
    
        #Sort
        bits = dict(sorted(bits.items()))
        
        #Compute objective
        Obj = Obj_from_bits(get_graph(H), bits)
    
        #Keep best sample
        if Obj > best_obj:
            best_obj = Obj
            best_bits = bits
    
    return {"best_bits": best_bits, "best_cut": best_obj, "shots": shots}

def MaxCut_fixed(H: nx.Graph, K, s, max_time = 10*60, QA = False):
    """Solve MaxCut for the graph H with bits in K fixed according to array s.
    
    Args:
        H: nx.graph.
        K: subset of nodes in H.
        s: bitstring with len(K) as dictionary.
        max_time: Time Limit for gurobi.
        QAOA: If True, MaxCut will be solved with QAOA. Else classically with Gurobi.
    Returns:
        ObjVal: objective value for MaxCut with nodes in K fixed according to s.
        V_bits: bit assignment of nodes in V1 (H.nodes\K) as dictionary for MaxCut. 
    """

    if QA == True:
        """"Use QAOA to solve MaxCut."""
        
        """Create dict for fixed bits."""
        fixed = {}
        for n in range(len(K)):
            fixed[K[n]] = s[K[n]]
        
        """Create problem class and QAOA class."""
        p = mcf.MaxCut(H, fixed, opt = False)
        QAO = QAOA(p, 3)
        
        """Get results:"""
        (result, angles) = QAO.execute()
        
        """If QAOA fails to optimize, check if problem is trivial. If not,
        try again with different angles."""
        if qaoa_failed(result, angles):
            if is_trivial_subproblem(H, fixed, p.free_qubits):
                bits = solve_trivial_subproblem(H, fixed, p.free_qubits)
                Obj = Obj_from_bits(get_graph(H), bits)
                print('trivial')
            else:
                """If QAOA fails to optimize, try again with different angles."""
                number_of_anglechanges = 0
                while angles[0]==angles[-1]: 
                    if number_of_anglechanges == 100:   #stop after 100 tries.
                        print("QAOA could not be performed")
                        
                    """Change one angle."""
                    angle_index = number_of_anglechanges % len(angles[0]) #select the next angle
                    angles[0][angle_index] += 0.2                      #change angle
                    QAO = QAOA(p, 3, angles = angles[0])               #QAOA with new angle
                    (result, angles) = QAO.execute()
                    number_of_anglechanges += 1
        
        state = QAO.current_state                   #save state after successful QAOA
        
        """Get qubits and measure."""
        qubits = undo_kronecker_qubits(np.array(state)) #undo Kronecker to get qubits
        
        """Measure qubits to get result."""
        data = decode_qaoa_result(H, p, fixed, qubits)
        Obj = data["best_cut"]
        bits = data["best_bits"]
    else:    
        """Solve MaxCut classical with gurobi."""
        """Create gurobi model"""
        p = gb.Model()
        p.setParam('TimeLimit', max_time)
        
        """Initialize nodes as variables"""
        V_dict = {}
        for n in H.nodes:
            V_dict[str(n)] = p.addVar(name = str(n), vtype = gb.GRB.BINARY)
            
        """Setting nodes in K to values in s through constraints"""
        p.addConstrs((V_dict[str(n)] == s[n] for n in K), name = 'c')
        
        """Objective"""
        C_i = [H[i][j]['weight']*(V_dict[str(i)] 
               + V_dict[str(j)] 
               - 2*V_dict[str(i)]*V_dict[str(j)]) for i, j in H.edges]
        p.setObjective(sum(C_i), gb.GRB.MAXIMIZE)
        
        """Optimize"""
        p.optimize()
        
        """Get results"""
        V_bits = {}
        for v in p.getVars():
            V_bits[v.VarName] = int(v.X)
        
        Obj = p.ObjVal
        bits = V_bits
        
    return Obj, bits

def Eq8(K: nx.Graph, s, ObjList, max_time=10*60):
    """Solve system of equations 8.
    
    Args:
        K: nx.graph.
        s: list of dictionary with all possible bitstring with len(K)
           (without identical cases through symmetry).
        ObjList: list of objective values for MaxCut corresponding to entries in s.
        max_time: Time Limit for gurobi.
    Returns:
        weights: solution to the system of equations 8.
    """
    
    """Create gurobi model"""
    p = gb.Model()
    p.setParam('TimeLimit', max_time)
    
    """Initialize error as variables"""
    error_dict = {}
    for n in range(len(s)):
        error_dict['e'+str(n)] = p.addVar(lb = 0, name = 'e'+str(n)
                                          , vtype = gb.GRB.CONTINUOUS)
        
    """Initialize c variable"""
    c = p.addVar(lb = float(-1*gb.GRB.INFINITY), name = 'c'
                 , vtype = gb.GRB.CONTINUOUS)
    
    """Initialize edges as variables"""
    E_dict = {}
    for n in K.edges:
        E_dict['K'+str(n)] = p.addVar(lb = float(-1*gb.GRB.INFINITY)
                                         , name = 'K'+str(n)
                                         , vtype = gb.GRB.CONTINUOUS)
        
    """Eq 8 as constraint"""
    for n in range(len(s)):
        constr = 0
        for m in K.edges:
            constr += (s[n][m[0]]+s[n][m[1]]
                       - 2*s[n][m[0]]*s[n][m[1]])*E_dict['K'+str(m)]
        p.addConstr(constr + c + error_dict['e'+str(n)] == ObjList[n])
        
    """Objective: Minimize error"""    
    err = 0
    for n in range(len(s)):
        err += error_dict['e'+str(n)]
    p.setObjective(err, gb.GRB.MINIMIZE)
    
    """Optimize"""
    p.optimize()
    
    """Get results"""
    weights = {}
    for v in p.getVars():
        weights[v.VarName] = v.X
        
    return weights

def Reweight(G: nx.graph, K, V1, V2, QA = False):
    """Decompose and reweight graph G.
    
    Args:
        G: nx.graph.
        K: vertex separator of G as list.
        V1, V2: remaining sets with V1>=V2 as lists
        QA: solve MaxCut classical or with QAOA
    Returns:
        G_new: decomposed and reweighted graph.
        cd: constant c.
        VbitsList: bit assignments as list of dictionary
        n_subproblems: number of subproblems
        stime: runtime
    """
    
    """Induce graph generated from K∪ V2."""
    H = nx.induced_subgraph(G, K + V2)
    
    """Initialize array S"""
    s = S_Array(K)
    
    """Initialize lists for objective values, node-bit-assignments and initialize subproblem and runtime counter."""
    ObjList = []
    VbitsList = []
    n_subproblems = 0
    stime = 0
    
    for ind in s:
        """
        Fix the qubits in K to either 0 or 1 with respect to the lth entry in s[ind]
        obj ← MaxCut objective value with fixed qubits in set K
        """
        n_subproblems += 1
        start_time = time.perf_counter()
        (obj,Vneu) = MaxCut_fixed(H, K, ind, QA=QA)
        stime += time.perf_counter() - start_time
        """Store data in lists."""
        ObjList.append(obj)
        VbitsList.append(Vneu.copy())
    
    
    """Create new fully connected graph with nodes K."""
    K_new = complete_graph_from_list(K)
    
    """Solve eq 8"""  
    new_weights = Eq8(K_new, s, ObjList)
    cd = new_weights['c']
    
    """Induce graph generated from K∪ V1"""
    G_new2 = nx.induced_subgraph(G, K + V1)
    G_new = nx.Graph(G_new2)                    #copy graph to unfreeze it
    
    """Reweight all edges of the new graph G_new between nodes in K"""
    for n in K_new.edges:
        G_new.add_weighted_edges_from([(n[0],n[1],new_weights['K'+str(n)])])    
      
    return G_new, cd, VbitsList, n_subproblems, stime


def Decomp(G: nx.graph, M, QA = False):
    """Decompose and reweight graph G.
    
    Args:
        G: nx.graph.
        M: predetermined parameter, terminate algorithm if K >= M
    Returns:
        Glist[i+1]: the final decomposed graph
        cdlist: list of all c_hats.
        Klist: list of all vertex separator sets K.
        VbitsList: list of solutions to MaxCut with fixed K.
        i: step
        step_records: data for analysis
        total_subproblems: number of subproblems
        stop_reason: reason for termination
        time: runtime
    """
    
    """Initialize i and lists for results"""
    i = 0
    cdList = []
    GList = []
    KList = []
    V1List = []
    V2List = []
    VbitsList = []
    step_records = []
    total_subproblems = 0
    subproblems_per_step = []
    
    """Get vertex separator K, remaining node sets with V1>V2"""
    (K,V1,V2) = VertexSep(G)
    
    """Append lists"""
    GList.append(G)
    time=0
    
    """Decompose and reweight graph G as long as the vertex seperator K_i of
    the new graph fulfills K_i < M."""
    while len(K) < M:
 
        (G_new, cd, VbitsList_new, n_step, t) = Reweight(G, K, V1, V2, QA=QA)
        time+=t
        total_subproblems += n_step
        subproblems_per_step.append(n_step)
        """Store constant c."""    
        cdList.append(cd)
        
        """Store data for analysis."""
        step_record = {
        "iteration": i,
        "num_nodes": G.number_of_nodes(),
        "num_edges": G.number_of_edges(),
        "separator_size": len(K),
        "V1_size": len(V1),
        "V2_size": len(V2),
        "separator_nodes": list(K),
        "V1_nodes": list(V1),
        "V2_nodes": list(V2),
        "num_free_qubits": len(V2),    
        "reweight_constant": cd,
        }
        step_records.append(step_record)

        """Store results."""
        KList.append(K)
        V1List.append(V1)
        V2List.append(V2)
        VbitsList.append(VbitsList_new)
        GList.append(G_new)
        G = G_new
        
        """Find vertex separator and remaining sets for the new graph."""
        (K,V1,V2) = VertexSep(G_new)        
        
        """Terminate if V2 is empty (no vertex separator was found)."""
        stop_reason = None
        if len(V2) == 0:
            print("break: V2 is empty")
            stop_reason = "no_separator"
            break
        
        if len(K) >= M:
            stop_reason = "separator_reached_M"
            print("break: separator reached M")
            break
        
        """Increment."""
        i += 1
       
    return GList[-1], cdList, KList, VbitsList, i, step_records, total_subproblems, stop_reason, time

def DecompStep(G: nx.Graph, K, V1, V2, QA=False):
    """Perform a single decomposition step on graph G with given K, V1, V2.

    Returns:
        G_new: reweighted graph after this step
        cd: constant c_hat for this step
        VbitsList_new: solutions to MaxCut with fixed K for this step
        n_step: number of subproblems solved in this step
        step_record: dict with basic info about this step (no solver data)
    """
    (G_new, cd, VbitsList_new, n_step) = Reweight(G, K, V1, V2, QA=QA)

    step_record = {
        "num_nodes_before": G.number_of_nodes(),
        "num_edges_before": G.number_of_edges(),
        "num_nodes_after": G_new.number_of_nodes(),
        "num_edges_after": G_new.number_of_edges(),
        "separator_size": len(K),
        "V1_size": len(V1),
        "V2_size": len(V2),
        "separator_nodes": list(K),
        "V1_nodes": list(V1),
        "V2_nodes": list(V2),
        "num_free_qubits": len(V2),    
        "reweight_constant": cd,
        "num_subproblems": n_step,
    }

    return G_new, cd, VbitsList_new, n_step, step_record, K, V1, V2

def get_results(decomp_result, decomp_objVal, decomp_G, cdlist, Klist, VbitsList):
    """Get the result for the original MaxCut problem after solving the 
    decomposed graph.
    
    Args:
        decomp_result: result for decomposed graph as list or dictionary
        decomp_objVal: objective value for decomposed problem.
        decomp_G: decomposed graph
        cdlist: list with all c's calculated in the decomposition.
        Klist: list of all Vertex Separator node sets K.
        VbitsList: results of MaxCut for fixed bits in K.
    Returns:
        result: result for original problem
        objVal: objective value for the original problem
    """
    
    """Calculate objective value for original problem."""
    objVal = decomp_objVal
    for n in range(len(cdlist)):
        objVal += cdlist[n] 
        
    """Convert decomp_result to dictionary if necessary."""
    result = result_to_dict(decomp_result, decomp_G)  

    """Search VbitsList for the corresponding result and update results list."""
    for n in range(len(Klist)):
        result.update(search_dict(VbitsList[len(Klist)-1-n], result, Klist[len(Klist)-1-n]))
    result = dict(sorted(result.items()))
    return result, objVal